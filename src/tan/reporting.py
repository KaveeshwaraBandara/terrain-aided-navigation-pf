"""Write numbers and tables for the LaTeX report — never typed by hand.

- :func:`write_macros` writes ``report/generated/<name>.tex`` with ``\\newcommand``
  definitions, e.g. ``\\EOneConvPfHillTwoThousand`` → ``97.3``; the report only uses
  these macros, so every number traces to a script output.
- :func:`write_table` writes a booktabs ``tabular`` (``report/tables/<name>.tex``)
  and the same data as CSV.
"""

from __future__ import annotations

import csv
import re
from collections.abc import Sequence
from pathlib import Path

from .config import REPO_ROOT

GENERATED = REPO_ROOT / "report" / "generated"
TABLES = REPO_ROOT / "report" / "tables"
FIGURES = REPO_ROOT / "report" / "figures"

_DIGITS = ["Zero", "One", "Two", "Three", "Four", "Five", "Six", "Seven", "Eight", "Nine"]


def macro_name(*parts: object) -> str:
    """CamelCase LaTeX command name from parts; digits are spelled out (LaTeX names are
    letters only): macro_name("e1", "conv", "pf", 2000) → 'EOneConvPfTwoZeroZeroZero'."""
    out = []
    for p in parts:
        for tok in re.split(r"[^A-Za-z0-9]+", str(p)):
            if not tok:
                continue
            tok = re.sub(r"\d", lambda m: _DIGITS[int(m.group())], tok)
            out.append(tok[0].upper() + tok[1:])
    name = "".join(out)
    if not name.isalpha():
        raise ValueError(f"bad macro name {name!r}")
    return name


def fmt(x: float, digits: int = 1) -> str:
    """Number for the report: thin-space thousands separators, fixed decimals."""
    if x is None or x != x:  # None or NaN
        return "--"
    s = f"{x:,.{digits}f}"
    return s.replace(",", "\\,")


def write_macros(name: str, macros: dict[str, str], header: str = "") -> Path:
    GENERATED.mkdir(parents=True, exist_ok=True)
    path = GENERATED / f"{name}.tex"
    lines = [f"% Generated by scripts — do not edit. {header}".rstrip()]
    for k in sorted(macros):
        if not k.isalpha():
            raise ValueError(f"macro name must be letters only: {k}")
        lines.append(f"\\newcommand{{\\{k}}}{{{macros[k]}}}")
    path.write_text("\n".join(lines) + "\n")
    return path


def write_table(
    name: str,
    header: Sequence[str],
    rows: Sequence[Sequence[object]],
    align: str | None = None,
    csv_header: Sequence[str] | None = None,
    csv_rows: Sequence[Sequence[object]] | None = None,
) -> tuple[Path, Path]:
    """booktabs tabular → ``report/tables/<name>.tex``; CSV → ``report/tables/<name>.csv``.

    ``csv_rows`` (raw numbers) default to ``rows`` (formatted strings).
    """
    TABLES.mkdir(parents=True, exist_ok=True)
    align = align or "l" + "r" * (len(header) - 1)
    tex = [f"\\begin{{tabular}}{{{align}}}", "\\toprule", " & ".join(header) + " \\\\", "\\midrule"]
    for r in rows:
        tex.append(" & ".join(str(c) for c in r) + " \\\\")
    tex += ["\\bottomrule", "\\end{tabular}"]
    tex_path = TABLES / f"{name}.tex"
    tex_path.write_text("% Generated by scripts — do not edit.\n" + "\n".join(tex) + "\n")
    csv_path = TABLES / f"{name}.csv"
    with open(csv_path, "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(csv_header or [re.sub(r"[\\$]", "", h) for h in header])
        w.writerows(csv_rows if csv_rows is not None else rows)
    return tex_path, csv_path
